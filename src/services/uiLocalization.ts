const DICTIONARIES: Record<NativeLanguageKey, Partial<Record<UiTranslationKey, string>>> = {
  English: EN_TRANSLATIONS,
  German: DE_TRANSLATIONS,
  Spanish: ES_TRANSLATIONS,
  French: FR_TRANSLATIONS,
  Italian: IT_TRANSLATIONS,
  Japanese: JA_TRANSLATIONS,
  Mandarin: ZH_TRANSLATIONS,
  Portuguese: PT_TRANSLATIONS
};

export function getUiDictionary(nativeLanguage?: string | null): Record<UiTranslationKey, string> {
  const key = normalizeNativeLanguage(nativeLanguage);
  if (key === 'German') return DE_TRANSLATIONS;
  if (key === 'English') return { ...EN_TRANSLATIONS };
  return { ...EN_TRANSLATIONS, ...(DICTIONARIES[key] || {}) };
}

export function t(
  key: UiTranslationKey,
  nativeLanguage?: string | null,
  vars?: Record<string, string | number>
): string {
  const uiKey = normalizeNativeLanguage(nativeLanguage);
  const template = DICTIONARIES[uiKey]?.[key] || EN_TRANSLATIONS[key] || key;
  if (!vars) return template;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_, name: string) => {
    const val = vars[name];
    return val !== undefined && val !== null ? String(val) : `{${name}}`;
  });
}


export function localizePracticedDuration(
  baseDisplay: { valueLabel: string; detailLabel: string },
  totalMinutes: number,
  totalSeconds?: number,
  nativeLanguage?: string | null
): { valueLabel: string; detailLabel: string } {
  const uiKey = normalizeNativeLanguage(nativeLanguage);
  if (uiKey !== 'German') return baseDisplay;

  const safeSecs =
    typeof totalSeconds === 'number' && Number.isFinite(totalSeconds)
      ? Math.max(0, Math.floor(totalSeconds))
      : Math.max(0, Math.floor((totalMinutes || 0) * 60));
  const mins = Math.floor(safeSecs / 60);
  const remSecs = safeSecs % 60;

  if (safeSecs === 0) {
    return {
      valueLabel: '0 Min.',
      detailLabel: 'Live-Räume, Übungen & Labor'
    };
  }
  if (mins === 0) {
    return {
      valueLabel: `${remSecs} Sek.`,
      detailLabel: 'Aktive Übungszeit erfasst'
    };
  }
  return {
    valueLabel: `${mins} Min.`,
    detailLabel: remSecs > 0 ? `${mins} Min. ${remSecs} Sek. in Räumen & Labor` : 'Live-Räume, Übungen & Labor'
  };
}


export function localizeLanguageName(langName: string, nativeLanguage?: string | null): string {
  const uiKey = normalizeNativeLanguage(nativeLanguage);
  const canonicalTarget = normalizeNativeLanguage(langName);
  const exactKnown = LANGUAGE_NAME_TRANSLATIONS[uiKey]?.[canonicalTarget];
  if (exactKnown && NATIVE_LANG_ALIASES[langName.trim().toLowerCase()]) {
    return exactKnown;
  }
  return langName;
}


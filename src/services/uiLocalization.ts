export function normalizeNativeLanguage(raw?: string | null): NativeLanguageKey {
  const cleaned = String(raw || '').trim().toLowerCase();
  if (!cleaned) return 'English';
  if (NATIVE_LANG_ALIASES[cleaned]) return NATIVE_LANG_ALIASES[cleaned];
  for (const [alias, canonical] of Object.entries(NATIVE_LANG_ALIASES)) {
    if (cleaned.startsWith(alias + ' ') || cleaned.includes(`(${alias})`)) {
      return canonical;
    }
  }
  return 'English';
}

export function getHtmlLangCode(nativeLanguage?: string | null): string {
  const key = normalizeNativeLanguage(nativeLanguage);
  return NATIVE_LANGUAGE_OPTIONS.find((opt) => opt.value === key)?.code || 'en';
}

export function getStoredNativeLanguage(): NativeLanguageKey | null {
  try {
    if (typeof localStorage === 'undefined') return null;
    const raw = localStorage.getItem(NATIVE_LANG_STORAGE_KEY);
    if (!raw || !raw.trim()) return null;
    return normalizeNativeLanguage(raw);
  } catch {
    return null;
  }
}

export function persistStoredNativeLanguage(nativeLanguage?: string | null): NativeLanguageKey {
  const normalized = normalizeNativeLanguage(nativeLanguage);
  try {
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem(NATIVE_LANG_STORAGE_KEY, normalized);
    }
    if (typeof document !== 'undefined' && document.documentElement) {
      document.documentElement.lang = getHtmlLangCode(normalized);
    }
  } catch {}
  return normalized;
}


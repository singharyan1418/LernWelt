/**
 * Translates UI-facing drill metadata (instruction, standard fallback hints & explanations)
 * into the user's native language while STRICTLY preserving the practice sentence, options,
 * correct answer, and scrambled word tokens in the learning language.
 */
export function localizeDrillChrome(drill: PracticeDrill, nativeLanguage?: string | null): PracticeDrill {
  const uiKey = normalizeNativeLanguage(nativeLanguage);
  if (uiKey === 'English') return drill;

  let nextInstruction = drill.instruction;
  let nextHint = drill.hint;
  let nextExplanation = drill.grammarExplanation;
  let nextSourceFact = drill.sourceFact;
  let nextWordClue = drill.wordClue;

  if (uiKey === 'German') {
    if (GERMAN_DRILL_EXACT_TEXT_MAP[drill.instruction]) {
      nextInstruction = GERMAN_DRILL_EXACT_TEXT_MAP[drill.instruction];
    } else if (/fill|blank|complete the sentence/i.test(drill.instruction) && drill.type === 'fill-blank') {
      nextInstruction = 'Wähle das passende Wort, um die Lücke im Satz zu füllen.';
    } else if (/arrange|order|rearrange|words/i.test(drill.instruction) && drill.type === 'sentence-ordering') {
      nextInstruction = 'Ordne die Wörter zu einem natürlichen Satz.';
    } else if (/type|guess|missing word/i.test(drill.instruction) && drill.type === 'guess-missing-word') {
      nextInstruction = 'Gib das fehlende Wort anhand von Kontext und Hinweis ein.';
    }

    if (nextHint) {
      if (/look at the meaning cue/i.test(nextHint)) {
        nextHint = nextHint.replace(
          /Look at the meaning cue:\s*"?([^"]*)"?/i,
          'Achte auf den Bedeutungshinweis: „$1“'
        );
      } else if (/think about how natural word order/i.test(nextHint)) {
        nextHint = 'Achte auf die natürliche Wortstellung im Satz (Subjekt, Verb und Ergänzungen).';
      } else if (/match the context/i.test(nextHint)) {
        nextHint = nextHint.replace(/Match the context:/i, 'Passend zum Kontext:');
      } else if (/starts with\s+["']?([a-zA-ZÀ-ÿ])["']?/i.test(nextHint)) {
        nextHint = nextHint.replace(/starts with\s+["']?([^"'.]+)["']?/i, 'Beginnt mit „$1“');
      }
    }

    if (nextExplanation) {
      if (/fits the grammar and meaning naturally in/i.test(nextExplanation)) {
        const answerMatch = nextExplanation.match(/^["']?([^"']+?)["']?\s+fits the grammar/i);
        if (answerMatch) {
          nextExplanation = `„${answerMatch[1]}“ passt grammatikalisch und inhaltlich am besten in diesen Kontext.`;
        }
      } else if (/natural spoken and written structure in/i.test(nextExplanation)) {
        nextExplanation = 'Die korrekte Satzstellung folgt der natürlichen Wortfolge dieser Sprache.';
      }
    }

    if (nextWordClue && /^Context clue:/i.test(nextWordClue)) {
      nextWordClue = nextWordClue.replace(/^Context clue:/i, 'Kontext:');
    }

    if (nextSourceFact && /^Synthesized from everyday/i.test(nextSourceFact)) {
      nextSourceFact = nextSourceFact.replace(
        /^Synthesized from everyday/i,
        'Erstellt aus authentischen Alltagsthemen:'
      );
    }
  }

  return {
    ...drill,
    // Learning-language practice fields remain strictly untouched:
    prompt: drill.prompt,
    options: drill.options,
    correctAnswer: drill.correctAnswer,
    orderedTokens: drill.orderedTokens,
    scrambledTokens: drill.scrambledTokens,
    language: drill.language,
    // UI/meta fields localized:
    instruction: nextInstruction,
    hint: nextHint,
    grammarExplanation: nextExplanation,
    wordClue: nextWordClue,
    sourceFact: nextSourceFact
  };
}

